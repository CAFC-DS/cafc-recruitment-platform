) s ON t.CODE = s.CODE
WHEN NOT MATCHED THEN INSERT (CODE, SORT_ORDER, IS_ACTIVE, ORIGIN) VALUES (s.CODE, NULL, s.ORIGIN = 'CODE', s.ORIGIN);

