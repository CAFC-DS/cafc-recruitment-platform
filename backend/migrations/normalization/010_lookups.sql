-- 010_lookups.sql
-- Lookup tables. Seeded from the code constants in backend/main.py (ORIGIN='CODE',
-- active) UNION every distinct value already present in the data (ORIGIN='DATA',
-- INACTIVE until a human decides to keep, fix or retire it). ROLES is seeded from
-- code only: a role is an authorization decision, never inferred from data.
-- PK/UNIQUE are informational in Snowflake; validate/ enforces them.

-- ---- ROLES ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ${CORE}.ROLES (
    ROLE_CODE         VARCHAR(50)  NOT NULL,
    DISPLAY_NAME      VARCHAR(100) NOT NULL,
    IS_INTERNAL       BOOLEAN      NOT NULL,
    SEES_ALL_REPORTS  BOOLEAN      NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ROLE_CODE)
);

MERGE INTO ${CORE}.ROLES t
USING (
    SELECT * FROM VALUES
        ('admin',          'Admin',          TRUE,  TRUE),
        ('senior_manager', 'Senior Manager', TRUE,  TRUE),
        ('manager',        'Manager',        TRUE,  TRUE),
        ('loan_manager',   'Loan Manager',   TRUE,  FALSE),
        ('scout',          'Scout',          TRUE,  FALSE),
        ('agent',          'Agent',          FALSE, FALSE),
        ('intel_reviewer', 'Intel Reviewer', FALSE, FALSE)
        AS v(ROLE_CODE, DISPLAY_NAME, IS_INTERNAL, SEES_ALL_REPORTS)
) s ON t.ROLE_CODE = s.ROLE_CODE
WHEN NOT MATCHED THEN INSERT (ROLE_CODE, DISPLAY_NAME, IS_INTERNAL, SEES_ALL_REPORTS)
    VALUES (s.ROLE_CODE, s.DISPLAY_NAME, s.IS_INTERNAL, s.SEES_ALL_REPORTS);

-- ---- Generic code lookups: REPORT_TYPES -------------------------------------
CREATE TABLE IF NOT EXISTS ${CORE}.REPORT_TYPES (
    CODE VARCHAR(100) NOT NULL, SORT_ORDER NUMBER(5,0), IS_ACTIVE BOOLEAN NOT NULL, ORIGIN VARCHAR(10) NOT NULL,
    CONSTRAINT PK_REPORT_TYPES PRIMARY KEY (CODE)
);
MERGE INTO ${CORE}.REPORT_TYPES t
USING (
    SELECT CODE, MIN(ORIGIN) AS ORIGIN FROM (
        SELECT column1 AS CODE, 'CODE' AS ORIGIN FROM VALUES ('Player Assessment'), ('Flag'), ('Clips')
        UNION ALL
        SELECT DISTINCT TRIM(REPORT_TYPE), 'DATA' FROM ${CORE}.SCOUT_REPORTS WHERE TRIM(REPORT_TYPE) <> ''
