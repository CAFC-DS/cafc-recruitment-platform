CREATE TABLE IF NOT EXISTS EMAIL_BATCHES (
 ID VARCHAR NOT NULL, PURPOSE VARCHAR NOT NULL, CREATED_BY NUMBER,
 PAYLOAD VARCHAR NOT NULL, STATE VARCHAR NOT NULL, CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS EMAIL_JOBS (
 ID VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL, RECIPIENT_KEY VARCHAR NOT NULL,
 RECIPIENT VARCHAR NOT NULL, SUBJECT VARCHAR NOT NULL, HTML_BODY VARCHAR NOT NULL,
 MODE VARCHAR NOT NULL, STATUS VARCHAR NOT NULL DEFAULT 'pending',
 ERROR VARCHAR, UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS EMAIL_LOG (
 ID VARCHAR NOT NULL, JOB_ID VARCHAR, RECIPIENT VARCHAR, ACTUAL_RECIPIENT VARCHAR,
 PURPOSE VARCHAR, SUBJECT VARCHAR, STATUS VARCHAR, ERROR VARCHAR,
 SENT_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS LIFECYCLE_MUTEX (ID NUMBER NOT NULL, REVISION NUMBER NOT NULL);
-- Deploy once with no lifecycle services running; standard Snowflake UNIQUE keys are not enforced.
MERGE INTO LIFECYCLE_MUTEX t USING (SELECT 1 ID) s ON t.ID=s.ID
WHEN NOT MATCHED THEN INSERT (ID, REVISION) VALUES (1, 0);
